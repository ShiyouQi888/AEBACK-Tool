export type Locale = keyof typeof catalogs
type CatalogKey = keyof typeof catalogs
export const localeOptions = Object.entries(catalogs).map(([locale, catalog]) => ({ locale: locale as Locale, label: catalog.nativeName }))
type I18nContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (source: string, values?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function readLocale(): Locale {
  try {
    const value = window.localStorage.getItem(storageKey)
    return value && value in catalogs ? value as CatalogKey : 'zh-CN'
  } catch {
    return 'zh-CN'
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(readLocale)
  const t = useCallback((source: string, values?: Record<string, string | number>) => {
    const messages = catalogs[locale].messages as Record<string, string>
    let message = messages[source] ?? source
    if (locale === 'en-US' && message === source) {
      const rowLimit = source.match(/^最多支持 ([\d,.]+) 行数据$/)
      const columnLimit = source.match(/^最多支持 ([\d,.]+) 列$/)
      const graphLimit = source.match(/^工程最多支持 ([\d,.]+) 个节点和 ([\d,.]+) 条关系。$/)
      const mapLimit = source.match(/^工程必须包含 1 到 ([\d,.]+) 个节点。$/)
      const crossLinkLimit = source.match(/^工程最多可包含 ([\d,.]+) 条跨节点连线。$/)
      const projectSize = source.match(/^工程文件不能超过 ([\d.]+) MB。$/)
      const fileSize = source.match(/^文件不能超过 ([\d.]+) MB$/)
      if (rowLimit) message = `A maximum of ${rowLimit[1]} data rows is supported.`
      else if (columnLimit) message = `A maximum of ${columnLimit[1]} columns is supported.`
      else if (graphLimit) message = `A project can contain up to ${graphLimit[1]} nodes and ${graphLimit[2]} relations.`
      else if (mapLimit) message = `A project must contain between 1 and ${mapLimit[1]} nodes.`
      else if (crossLinkLimit) message = `A project can contain up to ${crossLinkLimit[1]} cross-links.`
      else if (projectSize) message = `Project files must be ${projectSize[1]} MB or smaller.`
      else if (fileSize) message = `Files must be ${fileSize[1]} MB or smaller.`
    }
    if (!values) return message
    return message.replace(/\{(\w+)\}/g, (placeholder, key: string) => String(values[key] ?? placeholder))
  }, [locale])

  useEffect(() => {
    document.documentElement.lang = locale
    try { window.localStorage.setItem(storageKey, locale) } catch { /* Keep the locale for this session. */ }
  }, [locale])

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
